-- Build the King's Gambit browser simulator: one self-contained HTML page.
-- Usage (from the KingsGambit folder):  lua scripts/build-simulator.lua
--
-- It inlines the REAL engine modules (no RealClient, SelfCheck, Core or UI) with the module registry, which
-- then injects their dependencies (see src/Registry.lua), a small JSON API
-- layer, and the page template into simulator/index.html. The page runs the
-- engine over a MockClient in the browser with fengari (Lua in JavaScript), so there is no second
-- implementation of the rules to drift. Inlined so it works from file:// and GitHub Pages alike.
local SRC = "src/"
local DIR = "simulator/"
local MODULES = { "Hash", "Standings", "Ledger", "Client", "MockClient", "Engine", "ItemFit", "Loot", "SimNetwork", "Sync", "MoltenCore", "AQ40", "Tokens", "Sim", "Scenarios" }

-- Pinned Lua-in-JS runtime, with a Subresource Integrity hash so a changed file is refused.
local FENGARI = '<script src="https://cdn.jsdelivr.net/npm/fengari-web@0.1.4/dist/fengari-web.js"' ..
    ' integrity="sha384-aqYZ5bBpWDOXcXQUTRXOLnaFjrqrMw1BiHjk/1cz75A3ytQtdNkW1QfTe7kTlLR6" crossorigin="anonymous"></script>'

local function read(path)
    local f = assert(io.open(path, "rb"), "cannot open " .. path)
    local s = f:read("a"):gsub("\r\n", "\n")
    f:close()
    return s
end

local parts = {
    "-- Generated by scripts/build-simulator.lua from src/. Do not edit.",
    "local SK = {}",
    "KG_SK = SK",
}
for _, name in ipairs({ "Registry", table.unpack(MODULES) }) do
    parts[#parts + 1] = ("-- ===== %s.lua ====="):format(name)
    parts[#parts + 1] = "do local chunk = function(...)"
    parts[#parts + 1] = read(SRC .. name .. ".lua")
    parts[#parts + 1] = 'end; chunk("KingsGambit", SK) end'
end
parts[#parts + 1] = "SK:Resolve()"
local engine = table.concat(parts, "\n")
assert(not engine:find("</script", 1, true), "engine source must not contain </script")
local api = read(DIR .. "src/api.lua")
assert(not api:find("</script", 1, true), "api source must not contain </script")

local html = read(DIR .. "src/template.html")
local function sub(marker, text)
    local a, b = html:find(marker, 1, true)
    assert(a, "template is missing " .. marker)
    html = html:sub(1, a - 1) .. text .. html:sub(b + 1)
end
sub("<!--KG_FENGARI-->", FENGARI)
sub("<!--KG_ENGINE-->", '<script type="application/lua">\n' .. engine .. "\n</script>")
sub("<!--KG_API-->", '<script type="application/lua">\n' .. api .. "\n</script>")

local f = assert(io.open(DIR .. "index.html", "wb"))
f:write(html)
f:close()
print(("Wrote %sindex.html (%d KB, %d engine modules)"):format(DIR, math.floor(#html / 1024), #MODULES))
