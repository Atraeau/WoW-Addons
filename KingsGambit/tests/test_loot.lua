H.section("Loot: the priority draft")
test("a player who needs several items picks one, then the next player is up", function()
    local s, engine = setup({ nitems = 2 })
    for _, p in ipairs { "C", "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need"); s:bid("B", 1, "need"); s:bid("B", 2, "pass")
    eq(s.phase, "main"); eq(s.turn.type, "pick"); eq(s.turn.player, "A-Realm"); eq(#s.turn.options, 2)
    local ok, why = s:pick("B", 2); assert(not ok); eq(why, "notyourturn")
    local ok2, why2 = s:pick("A", 7); assert(not ok2); eq(why2, "badpick")
    assert(s:pick("A", 2))
    eq(s.phase, "review", "B auto-wins item 1: it is the only thing B wanted")
    assert(s:confirm())
    eq(events(engine, "main", "Award")[1].data.item, "item:2"); eq(events(engine, "main", "Award")[2].data.member, "B-Realm")
    eq(order(engine), "C,D,E,A,B")
end)
test("a pick timeout counts as a skip and the draft moves on", function()
    local s, _, client = setup({ nitems = 2 })
    for _, p in ipairs { "C", "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need"); s:bid("B", 1, "need"); s:bid("B", 2, "need")
    eq(s.turn.player, "A-Realm")
    client:advance(20)
    eq(s.turn.player, "B-Realm", "A timed out; B is up with a real choice")
    assert(s:skip("B"))
    eq(s.phase, "salvage", "both skipped: nobody drafted the items")
end)
test("pure SK: with no cap, a winner can win again from the bottom if the room passes", function()
    local s, engine = setup({ nitems = 2 })
    for _, p in ipairs { "B", "C", "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need")
    assert(s:pick("A", 1))
    eq(s.phase, "review"); assert(s:confirm())
    eq(#events(engine, "main", "Award"), 2); eq(order(engine), "B,C,D,E,A")
end)
test("skipping forfeits the rest of the tier for that player only", function()
    local s = setup({ nitems = 2 })
    for _, p in ipairs { "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need"); s:bid("B", 1, "need"); s:bid("B", 2, "need")
    s:bid("C", 1, "need"); s:bid("C", 2, "pass")
    assert(s:skip("A")); assert(s:pick("B", 1))
    -- A skipped; C only wanted item 1, which B took. B is the only bidder left for item 2,
    -- so B wins again from the bottom (no cap).
    eq(s.phase, "review"); eq(#s.pending, 2)
    eq(s.pending[1].member, "B-Realm"); eq(s.pending[1].item.link, "item:1")
    eq(s.pending[2].member, "B-Realm"); eq(s.pending[2].item.link, "item:2")
end)

