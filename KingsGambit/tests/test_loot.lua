test("ranked choice skips items already taken", function()
    local s = setup({ nitems = 2 })
    for _, p in ipairs { "C", "D", "E" } do for i = 1, 2 do s:bid(p, i, "pass") end end
    s:bid("A", 1, "need", { rank = 1 }); s:bid("A", 2, "pass")
    s:bid("B", 1, "need", { rank = 1 }); s:bid("B", 2, "need", { rank = 2 })
    eq(s.items[1].winner, "A-Realm"); eq(s.items[2].winner, "B-Realm", "B gets their second choice")
end)
test("without a full ranking the player is asked live, as before", function()
    local s = setup({ nitems = 2 })
    for _, p in ipairs { "B", "C", "D", "E" } do for i = 1, 2 do s:bid(p, i, "pass") end end
    s:bid("A", 1, "need", { rank = 1 }); s:bid("A", 2, "need")
    eq(s.phase, "main"); eq(s.turn.type, "pick")
    local ok, why = s:bid("A", 1, "need", { rank = 0 }); assert(not ok); eq(why, "closed")
end)
test("a bad rank is refused", function()
    local s = setup()
    local ok, why = s:bid("A", 1, "need", { rank = 0 }); assert(not ok); eq(why, "badrank")
    local ok2, why2 = s:bid("A", 1, "need", { rank = 1.5 }); assert(not ok2); eq(why2, "badrank")
end)
test("a whispered list is ranked in the order written", function()
    local s = setup({ nitems = 3 })
    s:handleWhisper("A", "need 3, need 1, pass 2")
    eq(s.bids["A-Realm"][3].rank, 1); eq(s.bids["A-Realm"][1].rank, 2); eq(s.bids["A-Realm"][2].rank, nil)
end)
