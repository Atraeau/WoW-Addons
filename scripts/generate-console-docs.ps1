#requires -Version 7.0
<#
.SYNOPSIS
    Generate docs/console-commands.md: every console command and CVar the running client lists, from a WowApiExport dump.

.DESCRIPTION
    Reads the SavedVariables file produced by the WowApiExport addon (run /apiexport then /reload in game, with
    addon version 0.2.0 or later), takes the client's own console list (ConsoleGetAllCommands, with each CVar's
    current and default value) and writes one Markdown page, grouped by category, with the help text the game gives.
    Use your browser's find (Ctrl+F) to search it, as in the in-game console.

.PARAMETER Path
    Path to WowApiExport.lua. If omitted it is found under the game's WTF folder using wow-dev.config.json.

.PARAMETER ApiJson
    A prebuilt api.json (as docs/api.json) instead of the game dump.

.PARAMETER Out
    Output file. Default: <repo>/docs/console-commands.md

.EXAMPLE
    .\scripts\generate-console-docs.ps1
#>
[CmdletBinding()]
param(
    [string]$Path,
    [string]$ApiJson,
    [string]$Out
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding $false

if (-not $Out) { $Out = Join-Path $repoRoot 'docs/console-commands.md' }

# --- Read the payload ------------------------------------------------------
$json = $null
if ($ApiJson) {
    if (-not (Test-Path $ApiJson)) { throw "api.json not found: $ApiJson" }
    $json = Get-Content -Raw -LiteralPath $ApiJson
} else {
    if (-not $Path) {
        $config = Get-Content (Join-Path $repoRoot 'wow-dev.config.json') -Raw | ConvertFrom-Json
        $wtf = Join-Path (Join-Path $config.gamePath $config.flavorDir) 'WTF'
        $candidates = Get-ChildItem -Path $wtf -Recurse -Filter 'WowApiExport.lua' -ErrorAction SilentlyContinue |
            Sort-Object LastWriteTime -Descending
        if (-not $candidates) { throw "Could not find WowApiExport.lua under $wtf`nRun /apiexport then /reload in game first." }
        $Path = $candidates[0].FullName
        Write-Host "Using dump: $Path" -ForegroundColor Gray
    }
    $rawFile = Get-Content -Raw -LiteralPath $Path
    $b64Match = [regex]::Match($rawFile, 'WowApiExportB64\s*=\s*"([A-Za-z0-9+/=]*)"')
    if (-not ($b64Match.Success -and $b64Match.Groups[1].Value.Length -gt 0)) {
        throw "WowApiExportB64 not found (or empty) in $Path. Re-run /apiexport then /reload."
    }
    $json = [System.Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($b64Match.Groups[1].Value))
}
$data = $json | ConvertFrom-Json

$commands = @($data.consoleCommands)
if ($commands.Count -eq 0) {
    throw "This dump has no console commands. Update the WowApiExport addon (0.2.0 or later), run /apiexport, then /reload."
}

function Esc([string]$text) {
    if ([string]::IsNullOrEmpty($text)) { return '' }
    return (($text -replace '\|', '\|') -replace "\r?\n", ' ').Trim()
}
# A Markdown code span; a value that contains a backtick (the console key) needs a longer fence.
function Code([string]$text) {
    $t = Esc $text
    if ($t.Contains([string][char]96)) { return '`` ' + $t + ' ``' }
    return '`' + $t + '`'
}
function Cell([string]$text) {
    $t = Esc $text
    if ($t.Length -eq 0) { return '' }
    return $t
}

$meta = $data.meta
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Console commands and CVars')
[void]$sb.AppendLine('')
[void]$sb.AppendLine("Everything the running client lists in its console, from the client's own command list (``ConsoleGetAllCommands``): build $($meta.build), interface $($meta.interface), exported $($meta.exportedAt). $($commands.Count) entries.")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Search with your browser''s find (Ctrl+F). In game, open the console with `/console enable`, then the ` or ~ key; change a CVar with `/console <name> <value>` (or `/run SetCVar("<name>", value)`), and read one with `/run print(GetCVar("<name>"))`. A command with a default value is a CVar: `default` is what it resets to. Generated by `scripts/generate-console-docs.ps1` from a `WowApiExport` dump; do not edit by hand.')
[void]$sb.AppendLine('')

$byCategory = $commands | Group-Object { if ($_.category) { [string]$_.category } else { 'Uncategorized' } } | Sort-Object Name
[void]$sb.AppendLine('## Categories')
[void]$sb.AppendLine('')
foreach ($g in $byCategory) {
    $anchor = ($g.Name.ToLower() -replace '[^a-z0-9]+', '-').Trim('-')
    [void]$sb.AppendLine("- [$($g.Name)](#$anchor) ($($g.Count))")
}
[void]$sb.AppendLine('')

foreach ($g in $byCategory) {
    [void]$sb.AppendLine("## $($g.Name)")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('| Command | Type | Value | Default | Help |')
    [void]$sb.AppendLine('|---|---|---|---|---|')
    foreach ($c in ($g.Group | Sort-Object { [string]$_.command })) {
        $cmd = Code $c.command
        $value = if ($null -ne $c.value -and "$($c.value)" -ne '') { Code "$($c.value)" } else { '' }
        $default = if ($null -ne $c.default -and "$($c.default)" -ne '') { Code "$($c.default)" } else { '' }
        [void]$sb.AppendLine("| $cmd | $(Cell ([string]$c.commandType)) | $value | $default | $(Cell $c.help) |")
    }
    [void]$sb.AppendLine('')
}

$text = ($sb.ToString() -replace "`r`n", "`n").TrimEnd("`n") + "`n"
[System.IO.File]::WriteAllText($Out, $text, $utf8)
Write-Host "Wrote $Out ($($commands.Count) commands in $($byCategory.Count) categories)" -ForegroundColor Green
