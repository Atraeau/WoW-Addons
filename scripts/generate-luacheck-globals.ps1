#requires -Version 7.0
<#
.SYNOPSIS
    Generate a luacheck read_globals list from the client's own API dump.

.DESCRIPTION
    Emits types/luacheck-globals.lua: a Lua file returning a sorted list of every
    global function, C_* namespace and Enum table the client exports, taken from
    api.json. .luacheckrc merges it into read_globals, so the hand-picked list
    stays readable while the lint knows the whole client. A warning for an
    undefined global then means one of two things: a real typo, or a function
    this client no longer has (GetContainerItemInfo, UnitAura, ...), which is
    exactly the signal a port needs.

.PARAMETER ApiJson
    Path to api.json. Default: <repo>/docs/api.json

.PARAMETER OutFile
    Output .lua file. Default: <repo>/types/luacheck-globals.lua
#>
[CmdletBinding()]
param(
    [string]$ApiJson,
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $ApiJson) { $ApiJson = Join-Path $repoRoot 'docs/api.json' }
if (-not $OutFile) { $OutFile = Join-Path $repoRoot 'types/luacheck-globals.lua' }
if (-not (Test-Path $ApiJson)) { throw "api.json not found: $ApiJson" }

$api = Get-Content $ApiJson -Raw | ConvertFrom-Json -AsHashtable
$names = [System.Collections.Generic.HashSet[string]]::new()

# Global functions and namespaces as the client lists them
foreach ($k in $api.globals.Keys) { [void]$names.Add($k) }
# Namespaces declared per system (C_Secrets, C_PetInfo, ...)
foreach ($s in $api.systems) {
    if ($s.namespace) { [void]$names.Add($s.namespace) }
}
# Enum is a single Lua table; one entry covers Enum.*
[void]$names.Add('Enum')

$valid = $names | Where-Object { $_ -match '^[A-Za-z_][A-Za-z0-9_]*$' } | Sort-Object -CaseSensitive
$build = $api.meta.build
$iface = $api.meta.interface

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("-- Generated by scripts/generate-luacheck-globals.ps1 from docs/api.json")
[void]$sb.AppendLine("-- (client build $build, interface $iface). Do not edit; regenerate after a client update.")
[void]$sb.AppendLine("-- Loaded by .luacheckrc and merged into read_globals.")
[void]$sb.AppendLine("return {")
foreach ($n in $valid) { [void]$sb.AppendLine("`t`"$n`",") }
[void]$sb.AppendLine("}")

$dir = Split-Path -Parent $OutFile
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $OutFile with $($valid.Count) globals (build $build)." -ForegroundColor Green
