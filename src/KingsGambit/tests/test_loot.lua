H.section("Loot: whisper fallback")
test("whispers are parsed in all the accepted forms", function()
    local P = Loot.ParseWhisper
    local function one(text, n) local a = assert(P(text, n)); eq(#a, 1); return a[1] end
    local a = one("need", 1); eq(a.item, 1); eq(a.kind, "need")
    a = one("  NEED ", 1); eq(a.kind, "need")
    a = one("2 off", 3); eq(a.item, 2); eq(a.kind, "off")
    a = one("pass 3", 3); eq(a.item, 3); eq(a.kind, "pass")
    a = one("#1: os", 2); eq(a.item, 1); eq(a.kind, "off")
    a = one("1 gift Aldric", 2); eq(a.kind, "gift"); eq(a.to, "aldric")
    a = one("gift Aldric", 1); eq(a.item, 1)
    a = one("pass", 3); eq(a.item, nil, "a bare pass applies to every item")
    local many = assert(P("1 need, 2 pass; 3 off", 3)); eq(#many, 3); eq(many[3].kind, "off")
end)
test("unclear whispers are rejected with a reason", function()
