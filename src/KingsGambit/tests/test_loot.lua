-- Loot session and draft engine tests. Members A..E start in that order (A on top).
local H = ...
local SK, test, eq = H.SK, H.test, H.eq
local MockClient, Engine, Loot = SK.modules.MockClient, SK.modules.Engine, SK.modules.Loot

-- opts: cfg (session config), members, raid (default A..E), candidates (loot candidates), nitems.
local function setup(o)
    o = o or {}
    local client = MockClient.New({ name = "Raidlead" })
    local engine = Engine.New(client)
    engine:CreateList("main", "Main")
    for _, n in ipairs(o.members or { "A", "B", "C", "D", "E" }) do
        engine:Append("main", "AddMember", { member = n, class = "WARRIOR" })
    end
    client:setRaid(o.raid or { "A", "B", "C", "D", "E" },
        { leader = "A", lootMethod = "master", masterLooter = "Raidlead" })
    local drops, items = {}, {}
    for i = 1, (o.nitems or 1) do
        drops[i] = { link = "item:" .. i, candidates = o.candidates }
        items[i] = { link = "item:" .. i, slot = i }
    end
    client:dropLoot(drops)
    local session = Loot.NewSession(engine, o.cfg)
    assert(session:start(items))
    return session, engine, client
end

local function order(engine, list) return table.concat(engine:Get(list or "main").state.order, ",") end

-- Everyone answers every item; `answers` maps player -> kind (or { kind, extra }) for all items.
local function answerAll(s, itemId, answers)
    for p, a in pairs(answers) do
        if type(a) == "table" then assert(s:bid(p, itemId, a[1], a[2])) else assert(s:bid(p, itemId, a)) end
    end
end

local function events(engine, list, type_)
    local out = {}
    for _, ev in ipairs(engine:Get(list).events) do
        if not type_ or ev.type == type_ then out[#out + 1] = ev end
    end
    return out
end

