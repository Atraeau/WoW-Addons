H.section("MockClient: loot")
local function lootRaid()
    local h = newClient()
    h:setRaid({ "Raidlead", "Aldric", "Mirel" }, { leader = "Raidlead", lootMethod = "master", masterLooter = "Raidlead" })
    h:dropLoot({ { link = "item:1", itemId = 1 }, { link = "item:2", itemId = 2, candidates = { "Aldric" } } })
    return h
end
test("dropLoot opens slots and announces them", function()
    local h, got = newClient(), nil
    h:setRaid({ "Raidlead", "Aldric" }, { leader = "Raidlead", lootMethod = "master", masterLooter = "Raidlead" })
    h:on("loot.opened", function(p) got = p.slots end)
    h:dropLoot({ { link = "item:1" } })
    eq(#got, 1); eq(#h:lootSlots(), 1); eq(h:candidates(1)[1], "Raidlead-Realm")
end)
test("give hands out an item once, and closes the window when empty", function()
    local h, cleared, closed = lootRaid(), {}, false
    h:on("loot.slotCleared", function(p) cleared[#cleared + 1] = p.slot end)
    h:on("loot.closed", function() closed = true end)
    assert(h:isMasterLooter())
    assert(h:give(1, "Mirel"))
    local ok, why = h:give(1, "Aldric"); assert(not ok); eq(why, "gone")
    assert(not closed); assert(h:give(2, "Aldric")); assert(closed)
    eq(table.concat(cleared, ","), "1,2"); eq(#h:lootSlots(), 0); eq(#h.given, 2); eq(h.given[1].to, "Mirel-Realm")
end)
test("give fails with the right reason", function()
    local h = lootRaid()
    local _, why = h:give(2, "Mirel"); eq(why, "notcandidate")
    local _, why2 = h:give(9, "Mirel"); eq(why2, "gone")
    local other = newClient({ name = "Aldric" })
    other:setRaid({ "Raidlead", "Aldric" }, { lootMethod = "master", masterLooter = "Raidlead" })
    other:dropLoot({ { link = "item:1" } })
    local _, why3 = other:give(1, "Aldric"); eq(why3, "notml")
end)
test("itemInfo is nil until the item is cached, then item.info fires", function()
    local h, got = newClient(), nil
    h:setItemInfo("item:1", { name = "Cloak", ilvl = 71 }, { delayed = true })
    h:on("item.info", function(p) got = p.link end)
    eq(h:itemInfo("item:1"), nil)
    h:cacheItem("item:1")
    eq(got, "item:1"); eq(h:itemInfo("item:1").ilvl, 71); eq(h:itemInfo("item:404"), nil)
end)

H.section("MockClient: communication")
test("send needs a registered prefix and records what was sent", function()
    local h = newClient()
    local ok, why = h:send("KG", "hi", "RAID"); assert(not ok); eq(why, "noprefix")
    h:registerPrefix("KG")
    assert(h:send("KG", "hi", "RAID")); eq(#h.sent, 1); eq(h.sent[1].payload, "hi"); eq(h.sent[1].from, "Raidlead-Realm")
end)
test("send rejects oversize, bad channel and a missing whisper target", function()
    local h = newClient(); h:registerPrefix("KG")
    local _, a = h:send("KG", string.rep("x", 256), "RAID"); eq(a, "toolong")
    assert(h:send("KG", string.rep("x", 255), "RAID"), "255 bytes is the limit")
    local _, b = h:send("KG", "x", "SAY"); eq(b, "badchannel")
    local _, c = h:send("KG", "x", "WHISPER"); eq(c, "notarget")
end)
test("onSend sees outgoing messages, receive delivers a normalized event", function()
    local h, out, got = newClient(), nil, nil
    h:registerPrefix("KG")
    h.onSend = function(_, m) out = m end
    h:send("KG", "ping", "GUILD"); eq(out.payload, "ping")
    h:on("comms.received", function(p) got = p end)
    assert(not h:receive("OTHER", "x", "RAID", "Aldric"), "unregistered prefix is not delivered")
    assert(h:receive("KG", "pong", "RAID", "Aldric"))
    eq(got.sender, "Aldric-Realm"); eq(got.payload, "pong")
end)
test("whispers and announcements are recorded; serialize round-trips", function()
    local h = newClient()
    h:whisper("Tavi", "need?"); h:announce("Rolling", "RAID_WARNING")
    eq(h.sent[1].kind, "whisper"); eq(h.sent[1].target, "Tavi-Realm"); eq(h.sent[2].channel, "RAID_WARNING")
    local v = { a = { 1, 2 }, b = "x" }
    eq(Hash.Canon(h:deserialize(h:serialize(v))), Hash.Canon(v))
end)

H.section("MockClient: trade, storage, reload")
test("tradeableUntil counts down and expires", function()
    local h = newClient()
    h:setTradeable("item:1", 100); h:advance(40)
    eq(h:tradeableUntil("item:1"), 60); h:advance(61); eq(h:tradeableUntil("item:1"), nil)
end)
test("trades are reported as events", function()
    local h, closed = newClient(), nil
    h:on("trade.closed", function(p) closed = p end)
    h:setTrade({ partner = "Aldric", give = { "item:1" } }); eq(h:trade().partner, "Aldric-Realm")
    h:completeTrade("Aldric", { "item:1" }, {})
    assert(closed.completed); eq(closed.partner, "Aldric-Realm"); eq(h:trade(), nil)
end)
test("reload clears timers and handlers but keeps storage", function()
    local h, n = newClient(), 0
    h:storage().account.x = 1
    h:after(1, function() n = n + 1 end)
    h:on("world.entered", function() n = n + 10 end)
    h:reload(); h:advance(5); h:enterWorld()
    eq(n, 0); eq(h:storage().account.x, 1)
end)

H.section("MockClient: restriction")
test("restriction blocks send, is announced, and clears", function()
    local h = newClient(); h:registerPrefix("KG")
    local seen = {}
    h:on("comms.restrictionChanged", function(p) seen[#seen + 1] = tostring(p.restricted) end)
    h:setRestricted(true)
    local ok, why = h:send("KG", "x", "RAID"); assert(not ok); eq(why, "restricted")
    h:setRestricted(false); assert(h:send("KG", "x", "RAID"))
    eq(table.concat(seen, ","), "true,false")
end)
test("item.info carries the parsed item id", function()
    local h, got = newClient(), nil
    h:on("item.info", function(p) got = p end)
    h:cacheItem("|Hitem:1234::::|h[X]|h")
    eq(got.itemId, 1234)
end)
