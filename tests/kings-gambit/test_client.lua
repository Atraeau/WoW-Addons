H.section("MockClient: time and randomness")
test("advance fires timers in order, each seeing the right now()", function()
    local h, log = newClient(), {}
    h:after(5, function() log[#log + 1] = "b@" .. h:now() end)
    h:after(2, function() log[#log + 1] = "a@" .. h:now() end)
    h:advance(10)
    eq(table.concat(log, " "), "a@1002 b@1005"); eq(h:now(), 1010)
end)
test("every repeats, cancel stops it", function()
    local h, n = newClient(), 0
    local t = h:every(2, function() n = n + 1 end)
    h:advance(7); eq(n, 3)
    h:cancel(t); h:advance(10); eq(n, 3)
end)
test("a timer can schedule another timer", function()
    local h, fired = newClient(), false
    h:after(1, function() h:after(1, function() fired = true end) end)
    h:advance(3); assert(fired)
end)
test("serverTime is an integer that tracks the clock", function()
    local h = newClient({ unix = 5000 })
    h:advance(61.9)
    eq(h:serverTime(), 5061)
end)
test("seeded random is repeatable and in range", function()
    local a, b = newClient({ seed = 42 }), newClient({ seed = 42 })
    for _ = 1, 50 do
        local x = a:random(6)
        eq(x, b:random(6)); assert(x >= 1 and x <= 6 and x == math.floor(x))
    end
    local f = a:random(); assert(f >= 0 and f < 1)
end)

H.section("MockClient: identity and roster")
