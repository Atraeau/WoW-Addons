-- Client contract and MockClient behavior tests.
local H = ...
local SK, test, eq = H.SK, H.test, H.eq
local Hash, Client, MockClient = SK.modules.Hash, SK.modules.Client, SK.modules.MockClient

local function newClient(opts) return MockClient.New(opts or { name = "Raidlead", realm = "Realm" }) end
local function names(list) local t = {}; for i, v in ipairs(list) do t[i] = v end; return table.concat(t, ",") end

H.section("Hash.Decode")
test("Decode inverts Canon for nested data, strings, numbers and booleans", function()
    local v = { a = 1, b = { "x", "y:z,{}=", 3.5 }, c = true, d = false, e = "", f = -7 }
    local back = assert(Hash.Decode(Hash.Canon(v)))
    eq(Hash.Canon(back), Hash.Canon(v))
    eq(back.b[2], "y:z,{}=")
end)
test("Decode rejects malformed input", function()
    assert(not Hash.Decode("{s1:a=n1"), "truncated")
    assert(not Hash.Decode("s9:ab"), "short string")
    assert(not Hash.Decode("n1x"), "trailing junk")
    assert(not Hash.Decode(nil))
end)

