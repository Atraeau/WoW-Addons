-- Engine tests: persistence over a Client, isolation between engines.
local H = ...
local SK, test, eq = H.SK, H.test, H.eq
local MockClient, Engine = SK.modules.MockClient, SK.modules.Engine

local function newClient(name) return MockClient.New({ name = name or "Raidlead", realm = "Realm" }) end

H.section("Engine")
test("CreateList and Append use the Client's identity and clock", function()
    local h = newClient()
    local c = Engine.New(h)
    assert(c:CreateList("main", "Main"))
    h:advance(30)
    local ev = assert(c:Append("main", "AddMember", { member = "Aldric-Realm" }))
    eq(ev.author, "Raidlead-Realm"); eq(ev.ts, h:serverTime()); eq(ev.seq, 2)
    local _, err = c:CreateList("main", "Again"); eq(err, "exists")
    local _, err2 = c:Append("nope", "AddMember", {}); eq(err2, "nolist")
end)
test("a rebuilt engine restores the same chain from storage (simulated /reload)", function()
    local h = newClient()
    local c = Engine.New(h)
    c:CreateList("main", "Main")
    for _, n in ipairs { "A-Realm", "B-Realm", "C-Realm" } do c:Append("main", "AddMember", { member = n }) end
    c:Append("main", "Award", { member = "A-Realm", item = "Sword" })
    local head = c:Get("main").head
    h:reload()
    local c2 = Engine.New(h)
    eq(c2:Get("main").head, head)
    eq(table.concat(c2:Get("main").state.order, ","), "B-Realm,C-Realm,A-Realm")
    local ev = assert(c2:Append("main", "AddMember", { member = "D-Realm" }))
    eq(ev.seq, 6)
end)
test("tampered storage is reported and left untouched", function()
    local h = newClient()
    local c = Engine.New(h)
    c:CreateList("main", "Main"); c:Append("main", "AddMember", { member = "A-Realm" })
    h:storage().account.lists.main.events[2].data.member = "Evil-Realm"
    h:reload()
    local c2 = Engine.New(h)
    eq(c2:Get("main"), nil); eq(c2.problems.main.reason, "badhash"); eq(c2.problems.main.index, 2)
    eq(h:storage().account.lists.main.events[2].data.member, "Evil-Realm", "storage must not be repaired silently")
    assert(#h.printed == 1)
    local _, err = c2:CreateList("main", "Replacement"); eq(err, "exists")
end)
test("engines are isolated (no shared module state)", function()
    local a, b = Engine.New(newClient("Raidlead")), Engine.New(newClient("Other"))
    a:CreateList("main", "Main")
    eq(b:Get("main"), nil)
    assert(b:CreateList("main", "Main"))
    eq(#a:Get("main").events, 1); eq(#b:Get("main").events, 1)
    assert(a:Get("main") ~= b:Get("main"))
end)

H.section("Engine: large ledgers verify in the background")
local function bigStorage(n)
    local client = MockClient.New({ name = "Raidlead", realm = "Realm" })
    local engine = Engine.New(client)
    engine:CreateList("main", "Main")
    for i = 1, n do assert(engine:Append("main", "AddMember", { member = "M" .. i .. "-Realm" })) end
    return client
end
test("a large list loads at once with usable standings, and verifies in slices", function()
    local client = bigStorage(60)
    client:reload()
    local e = Engine.New(client, { syncVerifyLimit = 10, verifyBatch = 8 })
    eq(#e:Get("main").state.order, 60, "standings are available immediately")
    assert(not e:IsVerified("main"))
    client:advance(1)
    assert(e:IsVerified("main")); eq(next(e.problems), nil); eq(e.verifyTimer, nil, "the timer stops when done")
end)
test("a tampered event in a large list is caught by the background check, and the list is taken out of use", function()
    local client = bigStorage(60)
    client.storage().account.lists.main.events[45].data.member = "Evil-Realm"
    client:reload()
    local e = Engine.New(client, { syncVerifyLimit = 10, verifyBatch = 8 })
    assert(e:Get("main"), "it loads first (the rules still hold)")
    local corrupt
    e:OnChange(function(kind, list) if kind == "corrupt" then corrupt = list end end)
    client:advance(1)
    eq(e:Get("main"), nil); eq(e.problems.main.index, 45); eq(corrupt, "main")
    eq(client.storage().account.lists.main.events[45].data.member, "Evil-Realm", "saved data is left alone")
end)
test("structural damage in a large list is caught immediately", function()
    local client = bigStorage(60)
    table.remove(client.storage().account.lists.main.events, 30)
    client:reload()
    local e = Engine.New(client, { syncVerifyLimit = 10 })
    eq(e:Get("main"), nil); eq(e.problems.main.reason, "malformed")
end)
test("small lists are still verified immediately", function()
    local client = bigStorage(5)
    client.storage().account.lists.main.events[3].data.member = "Evil-Realm"
    client:reload()
    local e = Engine.New(client)
    eq(e.problems.main.reason, "badhash"); eq(e.problems.main.index, 3)
end)
