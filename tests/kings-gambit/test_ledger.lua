-- Ledger, standings and hash tests.
local H = ...
local SK, test, eq = H.SK, H.test, H.eq
local Hash, Standings, Ledger = SK.modules.Hash, SK.modules.Standings, SK.modules.Ledger
local function order(chain) return table.concat(chain.state.order, ",") end

-- Build a list with members A..E (A on top), authored by Raidleader.
local function newList(ts)
    local c = assert(Ledger.NewChain("main"))
    assert(Ledger.Append(c, "CreateList", { name = "Main" }, "Raidleader", ts or 1))
    for i, n in ipairs { "A", "B", "C", "D", "E" } do
        assert(Ledger.Append(c, "AddMember", { member = n, class = "WARRIOR" }, "Raidleader", 1 + i))
    end
    return c
end

H.section("Hash")
test("same data hashes the same regardless of key order", function()
    eq(Hash.Canon({ a = 1, b = { x = 1, y = 2 } }), Hash.Canon({ b = { y = 2, x = 1 }, a = 1 }))
    eq(Hash.Sum("hello"), Hash.Sum("hello"))
end)
test("different data hashes differently", function()
    assert(Hash.Sum("hello") ~= Hash.Sum("hellp"))
    assert(Hash.Canon({ a = "1" }) ~= Hash.Canon({ a = 1 }), "string vs number must differ")
end)
test("the hash algorithm is locked (golden values from two different Lua runtimes)", function()
    -- These two were computed in a browser (fengari, Lua 5.3 with 32-bit integers) with the first
    -- implementation. If they ever change, every stored ledger would stop verifying.
    eq(Hash.Sum("hello Fenn-Realm"), "3dcf24964da09ca2")
    eq(Hash.Sum("hello Zed-Realm"), "0dda1aa26cc53a36")
end)
test("hash is 16 hex chars", function() assert(Hash.Sum("x"):match("^%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x%x$")) end)

H.section("Standings")
test("members join at the bottom in order", function() eq(order(newList()), "A,B,C,D,E") end)
test("a win drops the winner to the bottom", function()
    local c = newList()
    assert(Ledger.Append(c, "Award", { member = "A", item = "Sword" }, "Raidleader", 10))
    eq(order(c), "B,C,D,E,A")
    eq(c.state.members.A.wins, 1)
    eq(c.state.members.A.lastWinSeq, 7)
end)
test("pass changes no position but counts upgrade passes", function()
    local c = newList()
    assert(Ledger.Append(c, "Pass", { member = "A", item = "Sword", kind = "upgrade" }, "Raidleader", 10))
    eq(order(c), "A,B,C,D,E")
    eq(c.state.members.A.upgradePasses, 1)
end)
test("gifting: award with a recipient, then re-route with Transfer", function()
    local c = newList()
    local ev = assert(Ledger.Append(c, "Award", { member = "E", item = "Ring", to = "A" }, "Raidleader", 10))
    eq(c.state.awards[ev.id].to, "A")
    assert(Ledger.Append(c, "Transfer", { award = ev.id, to = "B" }, "Raidleader", 11))
    eq(c.state.awards[ev.id].to, "B")
end)
test("invalid events are refused and leave state untouched", function()
    local c = newList()
    local before, n = Standings.Digest(c.state), #c.events
    assert(not Ledger.Append(c, "Award", { member = "Nobody", item = "X" }, "Raidleader", 10))
    assert(not Ledger.Append(c, "AddMember", { member = "A" }, "Raidleader", 10), "duplicate member")
    assert(not Ledger.Append(c, "MovePlayer", { member = "A", pos = 2 }, "Raidleader", 10), "no reason")
    assert(not Ledger.Append(c, "Bogus", {}, "Raidleader", 10))
    eq(Standings.Digest(c.state), before); eq(#c.events, n)
end)
test("MovePlayer correction requires a reason and moves exactly", function()
    local c = newList()
    assert(Ledger.Append(c, "MovePlayer", { member = "E", pos = "top", reason = "mis-award fix" }, "Raidleader", 10))
    eq(order(c), "E,A,B,C,D")
end)
test("Revert undoes the latest award exactly, and consecutive ones in order", function()
    local c = newList()
    local a1 = assert(Ledger.Append(c, "Award", { member = "B", item = "X" }, "Raidleader", 10))
    local a2 = assert(Ledger.Append(c, "Award", { member = "A", item = "Y" }, "Raidleader", 11))
    eq(order(c), "C,D,E,B,A")
    assert(not Ledger.Append(c, "Revert", { target = a1.id }, "Raidleader", 12), "cannot skip the newer award")
    assert(Ledger.Append(c, "Revert", { target = a2.id }, "Raidleader", 12))
    assert(Ledger.Append(c, "Revert", { target = a1.id }, "Raidleader", 13))
    eq(order(c), "A,B,C,D,E"); eq(c.state.members.B.wins, 0)
    assert(not c.state.members.B.lastWinSeq)
end)
test("Revert is refused once positions have shifted", function()
    local c = newList()
    local a = assert(Ledger.Append(c, "Award", { member = "A", item = "X" }, "Raidleader", 10))
    assert(Ledger.Append(c, "MovePlayer", { member = "E", pos = 1, reason = "fix" }, "Raidleader", 11))
    assert(not Ledger.Append(c, "Revert", { target = a.id }, "Raidleader", 12))
end)

H.section("Ledger")
test("identical inputs produce identical chains (determinism)", function()
    eq(newList().head, newList().head)
end)
test("Load replays a stored chain to the same head and standings", function()
    local c = newList()
    assert(Ledger.Append(c, "Award", { member = "A", item = "X" }, "Raidleader", 10))
    local r = assert(Ledger.Load("main", c.events))
    eq(r.head, c.head); eq(Standings.Digest(r.state), Standings.Digest(c.state))
    local s = assert(Standings.Replay(c.events))
    eq(Standings.Digest(s), Standings.Digest(c.state))
end)
test("tampering with any event is detected at that event", function()
    local c = newList()
    assert(Ledger.Append(c, "Award", { member = "A", item = "X" }, "Raidleader", 10))
    c.events[7].data.member = "E"
    local r, err, idx = Ledger.Load("main", c.events)
    assert(not r); eq(err, "badhash"); eq(idx, 7)
end)
test("removing an event from the middle is detected", function()
    local c = newList()
    table.remove(c.events, 3)
    local r, err = Ledger.Load("main", c.events)
    assert(not r); eq(err, "gap")
end)
test("receiving the same event twice is idempotent", function()
    local c = newList()
    local ev = assert(Ledger.Append(c, "Award", { member = "A", item = "X" }, "Raidleader", 10))
    eq(Ledger.Receive(c, ev), "duplicate"); eq(#c.events, 7)
end)
test("events sync between two replicas, gaps and forks are reported", function()
    local a = newList()
    local b = Ledger.NewChain("main")
    for _, ev in ipairs(a.events) do eq(Ledger.Receive(b, ev), "appended") end
    eq(b.head, a.head)
    local e1 = assert(Ledger.Append(a, "Award", { member = "A", item = "X" }, "Raidleader", 10))
    local e2 = assert(Ledger.Append(a, "Award", { member = "B", item = "Y" }, "Raidleader", 11))
    local _, err = Ledger.Receive(b, e2); eq(err, "gap")
    eq(Ledger.Receive(b, e1), "appended"); eq(Ledger.Receive(b, e2), "appended")
    eq(b.head, a.head)
    -- a rival event for an already-filled slot is a fork
    local rival = { v = 1, list = "main", seq = e1.seq, prev = e1.prev, ts = 10, author = "Raidleader",
        type = "Award", data = { member = "C", item = "X" } }
    rival.id = Ledger.EventId(rival)
    local _, ferr = Ledger.Receive(b, rival); eq(ferr, "fork")
end)

