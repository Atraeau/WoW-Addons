-- Loot session and draft engine tests. Members A..E start in that order (A on top).
local H = ...
local SK, test, eq = H.SK, H.test, H.eq
local MockClient, Engine, Loot = SK.modules.MockClient, SK.modules.Engine, SK.modules.Loot

-- opts: cfg (session config), members, raid (default A..E), candidates (loot candidates), nitems.
local function setup(o)
    o = o or {}
    local client = MockClient.New({ name = "Raidlead", realm = "Realm" })
    local engine = Engine.New(client)
    engine:CreateList("main", "Main")
    for _, n in ipairs(o.members or { "A", "B", "C", "D", "E" }) do
        engine:Append("main", "AddMember", { member = n .. "-Realm", class = "WARRIOR" })
    end
    client:setRaid(o.raid or { "A", "B", "C", "D", "E" },
        { leader = "A", lootMethod = "master", masterLooter = "Raidlead" })
    local drops, items = {}, {}
    for i = 1, (o.nitems or 1) do
        drops[i] = { link = "item:" .. i, candidates = o.candidates }
        items[i] = { link = "item:" .. i, slot = i }
    end
    client:dropLoot(drops)
    local session = Loot.NewSession(engine, o.cfg)
    assert(session:start(items))
    return session, engine, client
end

local function order(engine, list) return table.concat(engine:Get(list or "main").state.order, ","):gsub("%-Realm", "") end

-- Everyone answers every item; `answers` maps player -> kind (or { kind, extra }) for all items.
local function answerAll(s, itemId, answers)
    for p, a in pairs(answers) do
        if type(a) == "table" then assert(s:bid(p, itemId, a[1], a[2])) else assert(s:bid(p, itemId, a)) end
    end
end

local function events(engine, list, type_)
    local out = {}
    for _, ev in ipairs(engine:Get(list).events) do
        if not type_ or ev.type == type_ then out[#out + 1] = ev end
    end
    return out
end

H.section("Loot: bidding")
test("highest-position needer wins and is given the item once confirmed", function()
    local s, engine, client = setup()
    answerAll(s, 1, { A = "pass", B = "need", C = "need", D = "pass", E = "pass" })
    eq(s.phase, "review", "everyone answered, so bidding closed early")
    eq(#s.pending, 1); eq(s.pending[1].member, "B-Realm")
    eq(order(engine), "A,B,C,D,E", "nothing is written before confirm")
    local ok, failures = s:confirm(); assert(ok); eq(#failures, 0); eq(s.phase, "done")
    eq(client.given[1].to, "B-Realm"); eq(order(engine), "A,C,D,E,B")
    local awards = events(engine, "main", "Award")
    eq(#awards, 1); eq(awards[1].data.member, "B-Realm"); eq(awards[1].data.item, "item:1")
end)
test("unanswered players count as pass when the timer runs out", function()
    local s, _, client = setup()
    assert(s:bid("C", 1, "need"))
    eq(s.phase, "bidding"); client:advance(29); eq(s.phase, "bidding")
    client:advance(2)
    eq(s.phase, "review"); eq(s.pending[1].member, "C-Realm")
end)
test("an open-ended timer waits for the Master Looter", function()
    local s, _, client = setup({ cfg = { bidSeconds = 0 } })
    assert(s:bid("B", 1, "need"))
    client:advance(3600); eq(s.phase, "bidding")
    assert(s:resolveNow()); eq(s.phase, "review")
end)
test("extend adds time to a running bid timer", function()
    local s, _, client = setup()
    client:advance(25); assert(s:extend(30))
    client:advance(10); eq(s.phase, "bidding", "still open: 5 + 30 seconds remained")
    client:advance(30); eq(s.phase, "backstop", "nobody bid, so the item goes to the backstop")
end)
test("answers can be changed until bidding closes, then bids are refused", function()
    local s = setup()
    assert(s:bid("B", 1, "need")); assert(s:bid("B", 1, "pass"))
    s:resolveNow()
    local ok, why = s:bid("B", 1, "need"); assert(not ok); eq(why, "closed")
end)
test("bids are validated", function()
    local s = setup()
    local function why(...) local ok, w = s:bid(...); assert(not ok); return w end
    eq(why("Nobody", 1, "need"), "ineligible"); eq(why("A", 9, "need"), "noitem"); eq(why("A", 1, "roll"), "badkind")
    eq(why("A", 1, "gift"), "badtarget"); eq(why("A", 1, "gift", { to = "A" }), "badtarget")
end)
test("answerCount tracks progress for the Master Looter panel", function()
    local s = setup()
    s:bid("A", 1, "need"); s:bid("B", 1, "pass")
    local answered, total = s:answerCount(); eq(answered, 2); eq(total, 5)
end)
test("unlisted raiders are enrolled at the bottom (or excluded with autoEnroll off)", function()
    local s, engine = setup({ raid = { "A", "B", "Z" } })
    eq(order(engine), "A,B,C,D,E,Z"); assert(s.eligible["Z-Realm"])
    local s2, engine2 = setup({ raid = { "A", "B", "Z" }, cfg = { autoEnroll = false } })
    eq(order(engine2), "A,B,C,D,E"); assert(not s2.eligible["Z-Realm"])
end)

H.section("Loot: the priority draft")
test("a player who needs several items picks one, then the next player is up", function()
    local s, engine = setup({ nitems = 2 })
    for _, p in ipairs { "C", "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need"); s:bid("B", 1, "need"); s:bid("B", 2, "pass")
    eq(s.phase, "main"); eq(s.turn.type, "pick"); eq(s.turn.player, "A-Realm"); eq(#s.turn.options, 2)
    local ok, why = s:pick("B", 2); assert(not ok); eq(why, "notyourturn")
    local ok2, why2 = s:pick("A", 7); assert(not ok2); eq(why2, "badpick")
    assert(s:pick("A", 2))
    eq(s.phase, "review", "B auto-wins item 1: it is the only thing B wanted")
    assert(s:confirm())
    eq(events(engine, "main", "Award")[1].data.item, "item:2"); eq(events(engine, "main", "Award")[2].data.member, "B-Realm")
    eq(order(engine), "C,D,E,A,B")
end)
test("a pick timeout counts as a skip and the draft moves on", function()
    local s, _, client = setup({ nitems = 2 })
    for _, p in ipairs { "C", "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need"); s:bid("B", 1, "need"); s:bid("B", 2, "need")
    eq(s.turn.player, "A-Realm")
    client:advance(20)
    eq(s.turn.player, "B-Realm", "A timed out; B is up with a real choice")
    assert(s:skip("B"))
    eq(s.phase, "backstop", "both skipped: nobody drafted the items")
end)
test("pure SK: with no cap, a winner can win again from the bottom if the room passes", function()
    local s, engine = setup({ nitems = 2 })
    for _, p in ipairs { "B", "C", "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need")
    assert(s:pick("A", 1))
    eq(s.phase, "review"); assert(s:confirm())
    eq(#events(engine, "main", "Award"), 2); eq(order(engine), "B,C,D,E,A")
end)
test("skipping forfeits the rest of the tier for that player only", function()
    local s = setup({ nitems = 2 })
    for _, p in ipairs { "D", "E" } do s:bid(p, 1, "pass"); s:bid(p, 2, "pass") end
    s:bid("A", 1, "need"); s:bid("A", 2, "need"); s:bid("B", 1, "need"); s:bid("B", 2, "need")
    s:bid("C", 1, "need"); s:bid("C", 2, "pass")
    assert(s:skip("A")); assert(s:pick("B", 1))
    -- A skipped; C only wanted item 1, which B took. B is the only bidder left for item 2,
    -- so B wins again from the bottom (no cap).
    eq(s.phase, "review"); eq(#s.pending, 2)
    eq(s.pending[1].member, "B-Realm"); eq(s.pending[1].item.link, "item:1")
    eq(s.pending[2].member, "B-Realm"); eq(s.pending[2].item.link, "item:2")
end)

H.section("Loot: gifting")
test("a gift bid wins at the gifter's position and the item goes to the target", function()
    local s, engine, client = setup()
    answerAll(s, 1, { A = "pass", B = { "gift", { to = "E" } }, C = "pass", D = "pass", E = "pass" })
    eq(s.pending[1].member, "B-Realm"); eq(s.pending[1].to, "E-Realm")
    assert(s:confirm())
    eq(client.given[1].to, "E-Realm", "the item is handed to the gift target")
    local a = events(engine, "main", "Award")[1]; eq(a.data.member, "B-Realm"); eq(a.data.to, "E-Realm")
    eq(order(engine), "A,C,D,E,B", "the gifter pays the position")
end)

H.section("Loot: off-spec")
test("main need always beats off-spec", function()
    local s = setup()
    answerAll(s, 1, { A = "pass", B = "off", C = "need", D = "pass", E = "pass" })
    eq(s.pending[1].member, "C-Realm"); eq(s.pending[1].tier, "main"); eq(#s.pending, 1)
end)
test("off-spec bidders are enrolled lazily and winning moves only the off list", function()
    local s, engine = setup()
    answerAll(s, 1, { A = "pass", B = "off", C = "off", D = "pass", E = "pass" })
    eq(s.phase, "review"); eq(s.pending[1].type, "enroll"); eq(s.pending[2].type, "enroll")
    eq(s.pending[3].type, "award"); eq(s.pending[3].list, "off"); eq(s.pending[3].member, "B-Realm")
    assert(s:confirm())
    eq(order(engine, "main"), "A,B,C,D,E", "the main list is untouched by an off-spec win")
    eq(order(engine, "off"), "C,B", "enrolled in main order, then the winner drops to the bottom")
end)
test("an existing off list decides the off-spec order", function()
    local s, engine = setup()
    engine:CreateList("off", "Off"); engine:Append("off", "AddMember", { member = "C-Realm" }); engine:Append("off", "AddMember", { member = "B-Realm" })
    local s2 = Loot.NewSession(engine); engine:Get("main")
    s:cancel()
    local client = engine.client
    client:dropLoot({ { link = "item:1" } })
    assert(s2:start({ { link = "item:1", slot = 1 } }))
    answerAll(s2, 1, { A = "pass", B = "off", C = "off", D = "pass", E = "pass" })
    eq(s2.pending[1].member, "C-Realm", "C is above B on the off list, whatever the main order says")
end)

H.section("Loot: backstop and disenchant")
test("items nobody wants are offered lowest position first, no usability gate", function()
    local s, engine = setup()
    answerAll(s, 1, { A = "pass", B = "pass", C = "pass", D = "pass", E = "pass" })
    eq(s.phase, "backstop"); eq(s.turn.type, "claim"); eq(s.turn.player, "E-Realm")
    assert(s:decline("E")); eq(s.turn.player, "D-Realm")
    assert(s:claimItem("D"))
    eq(s.phase, "review"); eq(s.pending[1].tier, "backstop")
    assert(s:confirm())
    eq(order(engine), "A,B,C,E,D", "the claimer drops to the bottom like any win")
end)
test("a backstop claimer can gift the item up at claim time (the minor-upgrade proxy)", function()
    local s, engine, client = setup()
    answerAll(s, 1, { A = "pass", B = "pass", C = "pass", D = "pass", E = "pass" })
    local ok, why = s:claimItem("E", { to = "E" }); assert(not ok); eq(why, "badtarget")
    assert(s:claimItem("E", { to = "A" }))
    assert(s:confirm())
    eq(client.given[1].to, "A-Realm", "the top player gets the item")
    local a = events(engine, "main", "Award")[1]; eq(a.data.member, "E-Realm"); eq(a.data.to, "A-Realm")
    eq(order(engine), "A,B,C,D,E", "the bottom player was already at the bottom: the proxy cost nothing")
end)
test("a backstop offer that times out counts as a decline", function()
    local s, _, client = setup()
    answerAll(s, 1, { A = "pass", B = "pass", C = "pass", D = "pass", E = "pass" })
    client:advance(10); eq(s.turn.player, "D-Realm")
end)
test("only the player being offered may claim or decline", function()
    local s = setup()
    answerAll(s, 1, { A = "pass", B = "pass", C = "pass", D = "pass", E = "pass" })
    local ok, why = s:claimItem("A"); assert(not ok); eq(why, "notyourturn")
    local ok2, why2 = s:decline("A"); assert(not ok2); eq(why2, "notyourturn")
end)
test("if everyone declines the item goes to the disenchanter", function()
    local s, engine, client = setup({ cfg = { deHandler = "A" } })
    answerAll(s, 1, { A = "pass", B = "pass", C = "pass", D = "pass", E = "pass" })
    for _, p in ipairs { "E", "D", "C", "B", "A" } do assert(s:decline(p)) end
    eq(s.phase, "review"); eq(s.pending[1].type, "disenchant"); eq(s.pending[1].to, "A")
    assert(s:confirm())
    eq(client.given[1].to, "A-Realm")
    local de = events(engine, "main", "Disenchant")[1]; eq(de.data.item, "item:1"); eq(de.data.to, "A")
    eq(order(engine), "A,B,C,D,E", "disenchanting changes no position")
end)

H.section("Loot: distribution and ledger")
test("a failed hand-out is reported and never written to the ledger", function()
    local s, engine = setup({ candidates = { "A" } })
    answerAll(s, 1, { A = "pass", B = "need", C = "pass", D = "pass", E = "pass" })
    local ok, failures = s:confirm()
    assert(ok); eq(#failures, 1); eq(failures[1].stage, "give"); eq(failures[1].reason, "notcandidate")
    eq(#events(engine, "main", "Award"), 0); eq(order(engine), "A,B,C,D,E")
end)
test("explicit passes that carry a kind are recorded for the transparency stats", function()
    local s, engine = setup()
    answerAll(s, 1, { A = { "pass", { passKind = "upgrade" } }, B = "need", C = "pass", D = "pass", E = "pass" })
    assert(s:confirm())
    local p = events(engine, "main", "Pass"); eq(#p, 1); eq(p[1].data.member, "A-Realm"); eq(p[1].data.kind, "upgrade")
    eq(engine:Get("main").state.members["A-Realm"].upgradePasses, 1)
end)
test("the same inputs always produce the same ledger (determinism)", function()
    local function run()
        local s, engine = setup({ nitems = 2 })
        answerAll(s, 1, { A = "need", B = "need", C = "off", D = "pass", E = "pass" })
        answerAll(s, 2, { A = "need", B = "pass", C = "pass", D = "pass", E = "pass" })
        if s.turn and s.turn.type == "pick" then s:pick(s.turn.player, s.turn.options[1]) end
        s:confirm()
        return engine:Get("main").head
    end
    eq(run(), run())
end)
test("cancel discards a session without touching the ledger", function()
    local s, engine = setup()
    answerAll(s, 1, { A = "pass", B = "need", C = "pass", D = "pass", E = "pass" })
    assert(s:cancel()); eq(s.phase, "cancelled")
    local ok, why = s:confirm(); assert(not ok); eq(why, "notreview")
    eq(#events(engine, "main", "Award"), 0)
end)
test("session events fire in order", function()
    local s = Loot.NewSession((function() local _, e = setup(); return e end)())
    local seen = {}
    s:on("phase", function(p) seen[#seen + 1] = p.phase end)
    s:on("bid", function(p) seen[#seen + 1] = "bid:" .. p.kind end)
    s.engine.client:dropLoot({ { link = "item:1" } })
    assert(s:start({ { link = "item:1", slot = 1 } }))
    answerAll(s, 1, { A = "pass", B = "need", C = "pass", D = "pass", E = "pass" })
    assert(table.concat(seen, ","):find("bidding"), table.concat(seen, ","))
    eq(seen[#seen], "review")
end)

H.section("Loot: new ledger events")
test("Disenchant and Salvage validate their input", function()
    local _, engine = setup()
    assert(not engine:Append("main", "Disenchant", { item = "item:1" }), "needs a recipient")
    assert(engine:Append("main", "Disenchant", { item = "item:1", to = "A" }))
