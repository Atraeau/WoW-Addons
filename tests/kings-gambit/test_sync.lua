-- Multi-engine sync tests over SimNetwork: gossip, catch-up, loss, duplicates, reordering,
-- partitions and forks, restriction, chunking, and rejection of tampered events.
local H = ...
local SK, test, eq = H.SK, H.test, H.eq
local MockClient, Engine, Sync, SimNetwork = SK.modules.MockClient, SK.modules.Engine, SK.modules.Sync, SK.modules.SimNetwork

local seedCounter = 0
local function peer(name, net, cfg)
    seedCounter = seedCounter + 1
    local client = MockClient.New({ name = name, realm = "Realm", seed = seedCounter * 7919 })
    local engine = Engine.New(client)
    local sync = Sync.New(engine, cfg or { heartbeat = 5, firstHeartbeat = 0.5, firstJitter = 1 })
    net:attach(client)
    sync:start()
    return { name = name .. "-Realm", client = client, engine = engine, sync = sync }
end

local function head(p, list) local c = p.engine:Get(list or "main"); return c and c.head or "none" end
local function count(p, list) local c = p.engine:Get(list or "main"); return c and #c.events or 0 end
local function order(p, list) local c = p.engine:Get(list or "main"); return c and table.concat(c.state.order, ","):gsub("%-Realm", "") or "none" end

local function members(p, names, start)
    for _, n in ipairs(names) do assert(p.engine:Append("main", "AddMember", { member = n .. "-Realm" })) end
end

H.section("Sync: gossip and catch-up")
test("live events reach every peer", function()
    local net = SimNetwork.New()
    local a, b, c = peer("A", net), peer("B", net), peer("C", net)
    assert(a.engine:CreateList("main", "Main"))
    members(a, { "X", "Y", "Z" })
    net:advance(2)
    eq(count(b), 4); eq(head(b), head(a)); eq(head(c), head(a)); eq(order(c), "X,Y,Z")
end)
test("a late joiner catches up from the heartbeat, across several batches", function()
    local net = SimNetwork.New()
    local a = peer("A", net)
    assert(a.engine:CreateList("main", "Main"))
    local names = {}
    for i = 1, 45 do names[i] = "M" .. i end
    members(a, names)
    net:advance(1)
    local late = peer("Late", net)
    net:advance(15)
    eq(count(late), 46); eq(head(late), head(a))
end)
test("a peer that missed messages (loss) converges through heartbeats", function()
    local net = SimNetwork.New({ dropRate = 0.2, seed = 5 })
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main"))
    local names = {}
    for i = 1, 30 do names[i] = "M" .. i end
    members(a, names)
    net:advance(180)
    assert(net.stats.dropped > 0, "the network really dropped messages")
    eq(head(b), head(a)); eq(count(b), 31)
end)
test("duplicated and reordered messages are harmless", function()
    local net = SimNetwork.New({ duplicateRate = 0.6, jitter = 0.8, seed = 11 })
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main"))
    local names = {}
    for i = 1, 25 do names[i] = "M" .. i end
    members(a, names)
    net:advance(60)
    assert(net.stats.duplicated > 0)
    eq(head(b), head(a)); eq(count(b), 26)
end)
test("two peers writing alternately stay in step", function()
    local net = SimNetwork.New()
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    for i = 1, 5 do
        assert(a.engine:Append("main", "AddMember", { member = "A" .. i })); net:advance(1)
        assert(b.engine:Append("main", "AddMember", { member = "B" .. i })); net:advance(1)
    end
    eq(head(a), head(b)); eq(count(a), 11)
end)

H.section("Sync: partitions and forks")
test("a peer that was only behind catches up with no fork", function()
    local net = SimNetwork.New()
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    net:partition({ { "A-Realm" }, { "B-Realm" } })
    members(a, { "X", "Y", "Z" }); net:advance(10)
    eq(count(b), 1)
    net:heal(); net:advance(15)
    eq(head(b), head(a)); eq(count(b), 4)
    assert(not b.engine.db.orphans, "no orphans when nobody diverged")
end)
test("a fork resolves to the longer chain everywhere; the loser's events are kept as orphans", function()
    local net = SimNetwork.New()
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    net:partition({ { "A-Realm" }, { "B-Realm" } })
    members(a, { "X1", "X2", "X3" })
    members(b, { "Y1", "Y2", "Y3", "Y4", "Y5" })
    net:advance(10)
    assert(head(a) ~= head(b), "the histories really diverged")
    local resolved = {}
    a.sync:on("forkResolved", function(p) resolved[#resolved + 1] = "a:" .. p.winner end)
    b.sync:on("forkResolved", function(p) resolved[#resolved + 1] = "b:" .. p.winner end)
    net:heal(); net:advance(40)
    eq(head(a), head(b)); eq(count(a), 6); eq(order(a), "Y1,Y2,Y3,Y4,Y5")
    eq(#a.engine.db.orphans, 1); eq(#a.engine.db.orphans[1].events, 3); eq(a.engine.db.orphans[1].events[1].data.member, "X1-Realm")
    assert(not b.engine.db.orphans)
    eq(a.sync.stats.forksResolved, 1); eq(b.sync.stats.forksResolved, 0)
end)
test("equal-length forks tie-break the same way on both sides (earlier event wins)", function()
    local net = SimNetwork.New()
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    net:partition({ { "A-Realm" }, { "B-Realm" } })
    members(b, { "Y1", "Y2" })      -- B writes first (earlier timestamps)
    net:advance(5)
    members(a, { "X1", "X2" })
    net:advance(5)
    net:heal(); net:advance(40)
    eq(head(a), head(b)); eq(order(a), "Y1,Y2")
end)
test("a three-way split converges after healing", function()
    local net = SimNetwork.New()
    local a, b, c = peer("A", net), peer("B", net), peer("C", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    net:partition({ { "A-Realm" }, { "B-Realm" }, { "C-Realm" } })
    members(a, { "X1" }); members(b, { "Y1", "Y2" }); members(c, { "Z1", "Z2", "Z3" })
    net:advance(10); net:heal(); net:advance(90)
    eq(head(a), head(b)); eq(head(b), head(c)); eq(count(a), 4); eq(order(a), "Z1,Z2,Z3")
end)

H.section("Sync: robustness")
test("restricted sending queues events and delivers them when the restriction lifts", function()
    local net = SimNetwork.New()
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    a.client:setRestricted(true)
    members(a, { "X", "Y" })
    net:advance(6)
    eq(count(b), 1); assert(a.sync:status().pending > 0); eq(a.sync:status().blocked, "restricted")
    a.client:setRestricted(false); net:advance(2)
    eq(count(b), 3); eq(a.sync:status().pending, 0)
end)
test("a large event is split into frames and reassembled", function()
    local net = SimNetwork.New()
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main")); members(a, { "X" }); net:advance(1)
    a.client:clearSent()
    assert(a.engine:Append("main", "Award", { member = "X-Realm", item = string.rep("item-link-", 80) }))
    assert(#a.client.sent > 1, "needed several frames")
    for _, m in ipairs(a.client.sent) do assert(#m.payload <= 255) end
    net:advance(3)
    eq(head(b), head(a))
end)
test("a tampered event is rejected and does not change the receiver", function()
    local net = SimNetwork.New()
    local a, b = peer("A", net), peer("B", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    local before = head(b)
    local forged = { v = 1, list = "main", seq = count(b) + 1, prev = before, ts = 1760000100, author = "A-Realm",
        type = "AddMember", data = { member = "Evil-Realm" }, id = "deadbeefdeadbeef" }
    a.sync:post({ t = "E", list = "main", n = 2, events = { forged } }, "GUILD")
    net:advance(3)
    eq(head(b), before); assert(b.sync.stats.rejected >= 1)
end)
test("a peer with a corrupt list never adopts events into it", function()
    local net = SimNetwork.New()
    local a = peer("A", net)
    assert(a.engine:CreateList("main", "Main")); net:advance(1)
    a.engine.problems.main = { reason = "badhash", index = 2 }
    local st = a.engine:Receive("main", { id = "x" })
    eq(st, nil)
end)
test("identical histories give identical heads on independent runs (determinism)", function()
    local function run()
        local net = SimNetwork.New({ seed = 3, jitter = 0.3 })
        local a, b = peer("A", net), peer("B", net)
        assert(a.engine:CreateList("main", "Main"))
        members(a, { "X", "Y" }); net:advance(5)
        return head(b)
    end
    eq(run(), run())
end)
